class Command(BaseCommand):
    help = 'Create 81 original sample tasks, 6 text lessons and sample works. Does not create users/passwords.'
    def add_arguments(self, parser):
        parser.add_argument('--owner', required=True, help='Existing staff username')
    def handle(self, *args, **options):
        owner = get_user_model().objects.filter(username=options['owner'], is_staff=True).first()
        if not owner:
            raise CommandError('Create a staff user with createsuperuser first.')
        topics=[]
        for n,title in enumerate(TOPICS,1):
            topic,_=Topic.objects.get_or_create(number=n,defaults={'title':title})
            topics.append(topic)
            for k in range(1,4):
                statement,answer,solution,attachment=example(n,k)
                task,created=Task.objects.get_or_create(topic=topic,title=f'{title} · практика {k}',defaults={'statement':statement,'answer':answer,'solution':solution,'difficulty':'easy','source':'Инфокод · авторский вводный пример, не официальный КИМ'})
                if created and attachment:
                    task.attachment.save(f'{n:02d}-{k}.txt',ContentFile(attachment.encode('utf-8')))
        for i,(section_title,title,theory,question,options_list,correct,explanation) in enumerate(LESSONS,1):
            section,_=Section.objects.get_or_create(title=section_title,defaults={'order':i,'description':'Базовые понятия и первый шаг к практике.'})
            lesson,created=Lesson.objects.get_or_create(section=section,title=title,defaults={'order':1,'theory':theory,'minutes':15,'published':True})
            if created:
                QuizQuestion.objects.create(lesson=lesson,text=question,options=options_list,correct_index=correct,explanation=explanation)
                material=LessonFile(lesson=lesson,title='Конспект урока · TXT')
                material.file.save(f'lesson-{i}.txt',ContentFile((title+'\n\n'+theory).encode('utf-8')))
        for title,nums,kind,duration in [('Стартовая диагностика · 27 номеров',list(range(1,28)),'exam',235),('Логика и кодирование',[2,4,7,8,11,14,15],'test',45),('Первые алгоритмы на Python',[5,16,17,23,24],'test',40)]:
            if not owner.variant_set.filter(title=title).exists():
                create_variant(creator=owner,title=title,topics=[t for t in topics if t.number in nums],kind=kind,duration=duration,published=True)
        from learning.course_services import bootstrap_course
        bootstrap_course()
        self.stdout.write(self.style.SUCCESS('Ready: 27 topics, 81 introductory tasks, 6 lessons, 3 works. No video recordings included.'))
