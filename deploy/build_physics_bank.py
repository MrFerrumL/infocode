def choose(rng, true, false, k_true=2, total=5):
    """Pick statements: k_true true ones among `total`; answer = their numbers in increasing order."""
    picked = rng.sample(true, k_true) + rng.sample(false, total - k_true)
    rng.shuffle(picked)
    answer = ''.join(str(i + 1) for i, (text, ok) in enumerate(picked) if ok)
    text = '\n'.join(f'{i + 1}) {s}' for i, (s, _) in enumerate(picked))
    return text, answer, [s for s, ok in picked if ok]


