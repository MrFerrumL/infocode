def num(x, places=3):
    """2.5 → '2,5'; 3.0 → '3'; keeps up to `places` decimals."""
    if isinstance(x, Fraction):
        x = float(x)
    value = round(x, places)
    text = f'{value:.{places}f}'.rstrip('0').rstrip('.')
    return ('0' if text in ('-0', '') else text).replace('.', ',')


