def font(size):
    return ImageFont.truetype(FONT, size)


def graph(points, xlabel='t, с', ylabel='v, м/с', xmax=None, ymin=0, ymax=None, ystep=None, xstep=1):
    """Piecewise-linear graph on a grid, like in the exam."""
    xmax = xmax or max(x for x, _ in points)
    ymax = ymax if ymax is not None else max(y for _, y in points)
    ystep = ystep or max(1, round((ymax - ymin) / 6))
    w, h, left, bottom, top, right = 900, 560, 110, 80, 50, 60
    img = Image.new('RGB', (w, h), 'white')
    d = ImageDraw.Draw(img)
    sx = (w - left - right) / xmax
    sy = (h - top - bottom) / (ymax - ymin)
    X = lambda x: left + x * sx
    Y = lambda y: h - bottom - (y - ymin) * sy
    x = 0
    while x <= xmax + 1e-9:
        d.line([(X(x), Y(ymin)), (X(x), Y(ymax))], fill='#d9d9d9', width=1)
        d.text((X(x), Y(ymin) + 10), num(x), fill='black', font=font(22), anchor='mt')
        x += xstep
    y = ymin
    while y <= ymax + 1e-9:
        d.line([(X(0), Y(y)), (X(xmax), Y(y))], fill='#d9d9d9', width=1)
        d.text((X(0) - 12, Y(y)), num(y), fill='black', font=font(22), anchor='rm')
        y += ystep
    d.line([(X(0), Y(ymin)), (X(0), top - 25)], fill='black', width=2)
    d.line([(X(0), Y(0)), (w - right + 30, Y(0))], fill='black', width=2)
    d.polygon([(X(0), top - 35), (X(0) - 7, top - 18), (X(0) + 7, top - 18)], fill='black')
    d.polygon([(w - right + 40, Y(0)), (w - right + 23, Y(0) - 7), (w - right + 23, Y(0) + 7)], fill='black')
    d.text((X(0) + 14, top - 32), ylabel, fill='black', font=font(24))
    d.text((w - right + 42, Y(0) + 44), xlabel, fill='black', font=font(24), anchor='rm')
    d.line([(X(a), Y(b)) for a, b in points], fill='#1d4ed8', width=5)
    return img


def scale_picture(lo, hi, step, value, unit, title):
    """A straight instrument scale (like a ruler or a thermometer) with a pointer."""
    w, h, left, right = 1000, 230, 60, 60
    img = Image.new('RGB', (w, h), 'white')
    d = ImageDraw.Draw(img)
    marks = round((hi - lo) / step)
    X = lambda v: left + (v - lo) / (hi - lo) * (w - left - right)
    d.rectangle([left - 20, 70, w - right + 20, 150], outline='black', width=2, fill='#fafafa')
    labelled = max(1, round(marks / 10))
    for i in range(marks + 1):
        v = lo + i * step
        big = i % labelled == 0
        d.line([(X(v), 70), (X(v), 70 + (34 if big else 18))], fill='black', width=2 if big else 1)
        if big:
            d.text((X(v), 112), num(v), fill='black', font=font(22), anchor='mt')
    d.polygon([(X(value), 66), (X(value) - 11, 30), (X(value) + 11, 30)], fill='#dc2626')
    d.text((w / 2, 190), f'{title}, {unit}', fill='black', font=font(24), anchor='mt')
    return img


